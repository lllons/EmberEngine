/**
 * @ember/packager/compile — builds a standalone game executable.
 *
 * Owner: this file owns `.exe` production. An export is three things:
 *   1. the browser bundle (from `browser.ts`), inlined as base64 so the binary has no
 *      loose files next to it,
 *   2. a generated Deno entry that starts the same loopback host the editor uses,
 *   3. a `deno compile` invocation that produces `dist/<game>.exe`.
 *
 * The binary embeds its own runtime, so the player needs no Deno, Node or install step.
 */

import { join, resolve } from "node:path";
import { bundleGame } from "./browser.ts";
import { type ResolvedGame, slug, toFileUrl } from "./manifest.ts";

export interface ExportOptions {
  projectRoot: string;
  game: ResolvedGame;
  /** Output directory for the executable. Defaults to `<projectRoot>/dist`. */
  distDir?: string;
  /** Build staging directory. Defaults to `<projectRoot>/build/export/<game>`. */
  stageDir?: string;
}

export interface ExportResult {
  game: ResolvedGame;
  exePath: string;
  exeBytes: number;
  bundleBytes: number;
  /** Seconds spent in `deno compile`. */
  compileSeconds: number;
}

export async function exportGame(options: ExportOptions): Promise<ExportResult> {
  const { game, projectRoot } = options;
  const stageDir = options.stageDir ?? join(projectRoot, "build", "export", game.manifest.name);
  const distDir = options.distDir ?? join(projectRoot, "dist");

  const bundle = await bundleGame({ projectRoot, game, outDir: stageDir });
  await Deno.mkdir(distDir, { recursive: true });

  // The bundle travels as base64: no escaping problems, no files beside the exe.
  const encoded = new TextEncoder().encode(bundle.js).toBase64();
  await Deno.writeTextFile(
    join(stageDir, "game-data.ts"),
    `// Generated by @ember/packager. Embeds the browser bundle so the exe is self-contained.\n` +
      `export const GAME_DATA = {\n` +
      `  title: ${JSON.stringify(game.manifest.title)},\n` +
      `  width: ${game.manifest.width},\n` +
      `  height: ${game.manifest.height},\n` +
      `  bundle: ${JSON.stringify(encoded)},\n` +
      `} as const;\n`,
  );

  await Deno.writeTextFile(
    join(stageDir, "entry.exe.ts"),
    `// Generated by @ember/packager. Do not edit: re-run \`ember export\` instead.\n` +
      `import { servePlayer } from "${
        toFileUrl(join(projectRoot, "packages", "player", "host.ts"))
      }";\n` +
      `import { GAME_DATA } from "./game-data.ts";\n\n` +
      `const js = new TextDecoder().decode(Uint8Array.fromBase64(GAME_DATA.bundle));\n` +
      `const host = servePlayer({\n` +
      `  title: GAME_DATA.title,\n` +
      `  width: GAME_DATA.width,\n` +
      `  height: GAME_DATA.height,\n` +
      `  js,\n` +
      `  open: Deno.env.get("EMBER_NO_OPEN") !== "1",\n` +
      `});\n\n` +
      `console.log("EmberEngine: " + GAME_DATA.title + " is running.");\n` +
      `console.log("PLAYER_URL=" + host.url);\n` +
      `console.log("Close this window (Ctrl+C) to stop.");\n`,
  );

  const exePath = resolve(join(distDir, `${slug(game.manifest.name)}.exe`));
  const started = performance.now();
  const result = await new Deno.Command(Deno.execPath(), {
    args: [
      "compile",
      "--no-check",
      "--allow-net=127.0.0.1",
      "--allow-run",
      "--allow-env=EMBER_NO_OPEN",
      "--output",
      exePath,
      join(stageDir, "entry.exe.ts"),
    ],
    cwd: projectRoot,
    stdout: "piped",
    stderr: "piped",
  }).output();
  const compileSeconds = Math.round((performance.now() - started) / 100) / 10;

  if (!result.success) {
    const stderr = new TextDecoder().decode(result.stderr).trim();
    const stdout = new TextDecoder().decode(result.stdout).trim();
    throw new Error(`deno compile failed for "${game.manifest.title}":\n${stderr || stdout}`);
  }

  const info = await Deno.stat(exePath);
  return {
    game,
    exePath,
    exeBytes: info.size,
    bundleBytes: bundle.bytes,
    compileSeconds,
  };
}
