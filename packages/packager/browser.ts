/**
 * @ember/packager/browser — turns a game directory into one browser bundle.
 *
 * Owner: this file owns the browser build step. It generates a two-line entry module
 * (player host + the game's `createGame`) and runs `deno bundle`, which resolves the
 * workspace import map for us. Nothing here knows about HTTP or `.exe` packaging; both
 * `play` and `export` call it so the dev window and the shipped game run identical code.
 */

import { join } from "node:path";
import { type ResolvedGame, slug, toFileUrl } from "./manifest.ts";

export interface BundleOptions {
  /** Workspace root; `deno bundle` is run here so `deno.jsonc` is picked up. */
  projectRoot: string;
  game: ResolvedGame;
  /** Directory the generated entry and bundle are written to. */
  outDir: string;
}

export interface BundleResult {
  game: ResolvedGame;
  /** Bundled ES module, self-contained (no imports left). */
  js: string;
  entryPath: string;
  bundlePath: string;
  bytes: number;
}

/** Bundles the game for the browser. Throws with the compiler output on failure. */
export async function bundleGame(options: BundleOptions): Promise<BundleResult> {
  const { game, outDir } = options;
  await Deno.mkdir(outDir, { recursive: true });

  const entryPath = join(outDir, `${slug(game.manifest.name)}-player.ts`);
  const bundlePath = join(outDir, "player.js");

  // The generated entry is the whole contract between a game and the window host: the
  // game owns its session and frame clock, the player only paints it and maps input.
  // The host module is addressed by path so a changing package barrel cannot break a game.
  const playerModule = toFileUrl(join(options.projectRoot, "packages", "player", "browser.ts"));
  await Deno.writeTextFile(
    entryPath,
    `// Generated by @ember/packager. Do not edit: rebuild the game instead.\n` +
      `import { startPlayer } from ${JSON.stringify(playerModule)};\n` +
      `import { createGame } from "${toFileUrl(game.entryPath)}";\n\n` +
      `const game = createGame();\n` +
      `const host = game.createHost();\n` +
      `startPlayer({ title: game.title, viewport: host.session.viewport, host });\n`,
  );

  const result = await new Deno.Command(Deno.execPath(), {
    args: [
      "bundle",
      "--platform",
      "browser",
      "--no-check",
      "--output",
      bundlePath,
      entryPath,
    ],
    cwd: options.projectRoot,
    stdout: "piped",
    stderr: "piped",
  }).output();

  const stdout = new TextDecoder().decode(result.stdout).trim();
  const stderr = new TextDecoder().decode(result.stderr).trim();
  if (!result.success) {
    throw new Error(`deno bundle failed for "${game.manifest.title}":\n${stderr || stdout}`);
  }

  const js = await Deno.readTextFile(bundlePath);
  return {
    game,
    js,
    entryPath,
    bundlePath,
    bytes: new TextEncoder().encode(js).byteLength,
  };
}
