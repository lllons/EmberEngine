/**
 * @ember/editor/native/export — the editor's Export action.
 *
 * Owner: this file owns "turn the project the editor has open into a standalone `.exe`".
 * It is the app-side half of `@ember/packager`: the packager knows how a game becomes an
 * executable, this knows which game the editor currently holds and where its factory lives.
 *
 * A project opened with `--game <folder>` already has a module exporting `createGame`, so the
 * packager can use it directly. A project that only exists inside the editor (the empty
 * project, or a built-in example) has no module, so one is generated in the build folder that
 * re-exports the editor's factory. Either way the scenes come from the editor, so what the
 * file runs is what the window showed.
 */

import { dirname, join } from "node:path";
import { pathToFileURL } from "node:url";
import type { Scene } from "@ember/core";
import { type ExportResult, type ExportStep, exportGame } from "@ember/packager";
import type { Game } from "@ember/runtime";
import type { EditorFactorySource } from "../examples.ts";

export interface EditorExportRequest {
  /** The game the editor is editing (id, title and the scenes it was built from). */
  game: Game;
  /** Scenes as edited: the open scene instance plus the rest of the project's scenes. */
  scenes: Map<string, Scene>;
  /** Scene the exported game starts in. */
  startScene: string;
  /** Where the project's authored `.emberscene` files live. */
  sceneDirectory: string;
  workspaceRoot: string;
  /** A module that already exports `createGame` (a game folder opened with `--game`). */
  gameModulePath?: string | null;
  /** The editor factory to re-export when there is no game module (empty project, example). */
  factory?: EditorFactorySource | null;
  buildDirectory?: string;
  outputDirectory?: string;
  /** Stop after bundling (tests: proves the wiring without a 5 s compile). */
  skipCompile?: boolean;
  onStep?: (step: ExportStep) => void;
}

export interface EditorExportOutcome {
  result: ExportResult;
  /** Module the exported entry imports `createGame` from. */
  gameModulePath: string;
  /** The scene files handed to the packager, for reporting. */
  sceneNames: string[];
}

/**
 * The workspace the packager builds from: the nearest folder with a `deno.jsonc`, so an
 * executable launched from `dist/` still finds the engine's import map. Null when there is
 * no workspace above `start` at all (the editor then reports that export needs the repo).
 */
export async function findWorkspaceRoot(start = Deno.cwd()): Promise<string | null> {
  let directory = start;
  for (let depth = 0; depth < 8; depth++) {
    for (const name of ["deno.jsonc", "deno.json"]) {
      try {
        if ((await Deno.stat(join(directory, name))).isFile) return directory;
      } catch {
        // Keep walking towards the filesystem root.
      }
    }
    const parent = dirname(directory);
    if (parent === directory) break;
    directory = parent;
  }
  return null;
}

/** Source of the shim module a from-scratch project is exported through. */
export function editorGameModuleSource(factory: EditorFactorySource): string {
  const url = JSON.stringify(factory.moduleUrl);
  // A texture game re-exports its procedural textures too: the packager detects them by the
  // presence of `textureSources`, and without them every sprite exports as a placeholder.
  const textures = factory.textureExportName
    ? `export { ${factory.textureExportName} as textureSources } from ${url};\n`
    : "";
  return `// Generated by the Ember editor — the exported project's game factory.
// The project only exists inside the editor, so the executable re-exports the same factory
// the editor itself builds the game with.
export { ${factory.exportName} as createGame } from ${url};
${textures}`;
}

/** Path behind a `file:` URL, or null for any other protocol. */
export function modulePath(url: string): string | null {
  try {
    const parsed = new URL(url);
    if (parsed.protocol !== "file:") return null;
    const path = decodeURIComponent(parsed.pathname);
    // `/C:/...` is Windows' drive path with the URL's leading slash.
    return /^\/[A-Za-z]:/.test(path) ? path.slice(1) : path;
  } catch {
    return null;
  }
}

async function isFile(path: string): Promise<boolean> {
  try {
    return (await Deno.stat(path)).isFile;
  } catch {
    return false;
  }
}

/**
 * The real source file behind a factory's module URL.
 *
 * Run from source the URL is already a file on disk. A *compiled* editor reports URLs inside
 * its own virtual filesystem (`…/deno-compile-EmberEngine.exe/packages/editor/examples.ts`),
 * which the packager's child processes cannot import. The longest tail of that path that
 * exists in the workspace is the same source file, so the exported game imports what the
 * person exporting it can actually build.
 */
export async function resolveFactoryModule(
  url: string,
  workspaceRoot: string,
): Promise<string | null> {
  const path = modulePath(url);
  if (!path) return null;
  const root = workspaceRoot.replace(/\\/g, "/").replace(/\/$/, "");
  const normalized = path.replace(/\\/g, "/");
  // A compiled editor's temp extraction is a real file but not part of the project: its
  // sibling child process cannot rely on it staying, so the workspace copy wins.
  const inWorkspace = normalized === root || normalized.startsWith(`${root}/`);
  if (inWorkspace && await isFile(normalized)) return normalized;
  const parts = normalized.split("/").filter((part) => part.length > 0);
  let best: string | null = null;
  for (let index = parts.length - 1; index >= 0; index--) {
    const candidate = join(workspaceRoot, ...parts.slice(index));
    if (await isFile(candidate)) best = candidate;
  }
  return best;
}

/**
 * The scenes the packager should serialize: the project's registered scenes, with the open
 * scene taken from the editor so unsaved edits are what gets exported.
 */
export function scenesForExport(
  game: Game,
  openScene: Scene,
): Map<string, Scene> {
  const scenes = new Map<string, Scene>();
  for (const name of game.sceneNames()) {
    scenes.set(name, name === openScene.name ? openScene : game.createScene(name));
  }
  if (!scenes.has(openScene.name)) scenes.set(openScene.name, openScene);
  return scenes;
}

/** One line a caller can log or show in its status bar. */
export function describeEditorExport(outcome: EditorExportOutcome): string {
  const exe = outcome.result.exePath;
  const bytes = outcome.result.exeBytes;
  return exe
    ? `Exported ${exe} (${(bytes / 1024 / 1024).toFixed(1)} MiB, ${outcome.sceneNames.length} scenes)`
    : `Bundled ${outcome.result.bundlePath} (compile skipped)`;
}

/**
 * Exports the project the editor has open. Throws with the underlying tool output when the
 * bundle or the compile fails, so the editor can show the real reason.
 */
export async function exportEditorProject(
  request: EditorExportRequest,
): Promise<EditorExportOutcome> {
  const workspaceRoot = await findWorkspaceRoot(request.workspaceRoot);
  if (!workspaceRoot) {
    throw new Error(
      `no engine workspace above ${request.workspaceRoot}: exports need the engine folder (deno.jsonc), so run the editor from the repository`,
    );
  }
  const scenes = request.scenes;
  if (scenes.size === 0) throw new Error("nothing to export: the project has no scenes");
  const startScene = scenes.has(request.startScene)
    ? request.startScene
    : scenes.keys().next().value as string;

  let gameModulePath = request.gameModulePath ?? null;
  if (!gameModulePath) {
    if (!request.factory) {
      throw new Error("this project has no game module and no editor factory to export");
    }
    const factoryModule = await resolveFactoryModule(request.factory.moduleUrl, workspaceRoot);
    if (!factoryModule) {
      throw new Error(
        `cannot export this project: its factory module (${request.factory.moduleUrl}) is not in ${workspaceRoot} — run the editor from the engine folder (\`deno task editor\`) so the exported game can import its source`,
      );
    }
    const buildDirectory = request.buildDirectory ?? `${workspaceRoot}/build/${request.game.id}`;
    await Deno.mkdir(buildDirectory, { recursive: true });
    gameModulePath = `${buildDirectory}/editor-game.ts`;
    await Deno.writeTextFile(
      gameModulePath,
      editorGameModuleSource({ ...request.factory, moduleUrl: pathToFileURL(factoryModule).href }),
    );
  }

  const result = await exportGame({
    game: request.game,
    scenes,
    startScene,
    gameModulePath,
    gameDirectory: request.sceneDirectory,
    workspaceRoot,
    buildDirectory: request.buildDirectory,
    outputDirectory: request.outputDirectory,
    skipCompile: request.skipCompile,
    onStep: request.onStep,
  });

  return {
    result,
    gameModulePath,
    sceneNames: result.scenes,
  };
}

